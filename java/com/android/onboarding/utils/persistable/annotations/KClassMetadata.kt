package com.android.onboarding.utils.persistable.annotations

import android.os.PersistableBundle
import com.android.onboarding.utils.persistable.Persistable
import com.android.onboarding.utils.persistable.PersistableBundle
import com.android.onboarding.utils.persistable.PersistableDeserializer
import com.android.onboarding.utils.persistable.PersistableListSerializer
import com.android.onboarding.utils.persistable.PersistableMapDeserializer
import com.android.onboarding.utils.persistable.PersistableMapSerializer
import com.android.onboarding.utils.persistable.PersistablePersistableBundle
import com.android.onboarding.utils.persistable.PersistableSerializer
import com.android.onboarding.utils.persistable.PersistableString
import com.android.onboarding.utils.persistable.StrictPersistableListDeserializer
import com.android.onboarding.utils.persistable.getPersistable
import com.android.onboarding.utils.persistable.putPersistable
import kotlin.reflect.KClass

/** A marker interface for all classes generated by [PersistableAnnotation]. */
interface IPersistableAnnotation : Persistable

/**
 * Marker interface for [PersistableAnnotation] marked annotation companion objects. It is
 * automatically implemented by generated [IPersistableAnnotation] companions.
 *
 * Main use-case is lifting generated serializers to the target annotation companion.
 *
 * ```kotlin
 * @PersistableAnnotation
 * annotation class MyAnnotation(val value: String) {
 *   companion object: PersistableAnnotationCompanion<MyAnnotation, PMyAnnotation> by PMyAnnotation
 * }
 * ```
 *
 * @see PersistableAnnotationCompanionDelegate
 */
interface PersistableAnnotationCompanion<A : Annotation, P : IPersistableAnnotation> :
  PersistableSerializer<A>, PersistableDeserializer<P>

/**
 * Abstract base implementing [PersistableAnnotationCompanion] by delegating to [delegate]. This is
 * a compat option for cases where KAPT is used to generate stubs for the implementing class and
 * regular interface implementation by delegation cannot be used due to KAPT bugs in AOSP.
 *
 * Main use-case is lifting generated serializers to the target annotation companion.
 *
 * ```kotlin
 * @PersistableAnnotation
 * annotation class MyAnnotation(val value: String) {
 *   companion object: PersistableAnnotationCompanionDelegate<MyAnnotation, PMyAnnotation>(PMyAnnotation)
 * }
 * ```
 */
abstract class PersistableAnnotationCompanionDelegate<A : Annotation, P : IPersistableAnnotation>(
  delegate: PersistableAnnotationCompanion<A, P>
) : PersistableAnnotationCompanion<A, P> by delegate

/**
 * A container for annotation data extracted through [PersistableAnnotation.ExtractMetadata].
 *
 * @property name The [Class.name] extracted from the source class reference containing metadata.
 * @property canonicalName The [Class.canonicalName] extracted from the source class reference
 *   containing metadata.
 */
class KClassMetadata
private constructor(
  val name: String,
  val canonicalName: String,
  private val data: Map<out String, PersistableBundle>,
) : Persistable {
  /** Get all extracted annotations of [type][T]. */
  fun <T : IPersistableAnnotation> get(
    type: Class<T>,
    deserializer: PersistableDeserializer<T>,
  ): List<T> {
    val bundle = data[type.key] ?: return emptyList()
    return StrictPersistableListDeserializer(deserializer).fromPersistableBundle(bundle)
  }

  /** Get all extracted annotations of [type][T]. */
  @JvmSynthetic
  inline operator fun <reified T : IPersistableAnnotation> get(
    deserializer: PersistableDeserializer<T>
  ): List<T> = get(T::class.java, deserializer)

  override fun toPersistableBundle() = PersistableBundle {
    putString(KEY_NAME, name)
    putString(KEY_CANONICAL_NAME, canonicalName)
    putPersistable(
      KEY_DATA,
      data,
      PersistableMapSerializer(PersistableString, PersistablePersistableBundle),
    )
  }

  companion object : PersistableDeserializer<KClassMetadata> {
    private const val KEY_NAME = "NAME"
    private const val KEY_CANONICAL_NAME = "CANONICAL_NAME"
    private const val KEY_DATA = "DATA"

    private val Class<out IPersistableAnnotation>.key
      get() =
        declaredAnnotations.filterIsInstance<PersistableAnnotation.Generated>().single().sourceId

    override fun fromPersistableBundle(persistableBundle: PersistableBundle) =
      KClassMetadata(
        name = requireNotNull(persistableBundle.getString(KEY_NAME)),
        canonicalName = requireNotNull(persistableBundle.getString(KEY_CANONICAL_NAME)),
        data =
          requireNotNull(
            persistableBundle.getPersistable(
              KEY_DATA,
              PersistableMapDeserializer(
                PersistableString::rawFromPersistableBundle,
                PersistablePersistableBundle::rawFromPersistableBundle,
              ),
            )
          ),
      )

    /**
     * Extract [KClassMetadata] from [source].
     *
     * @param source The class reference to extract the metadata from.
     * @param targets All annotation types which should be extracted.
     * @param converters An index of annotation type to converter of that annotation type to its
     *   persistable variant.
     * @param keys An index of annotation types to their keys for erased grouping.
     */
    @Suppress("NewApi")
    fun extract(
      source: KClass<*>,
      targets: Array<KClass<out Annotation>>,
      converters: Map<KClass<out Annotation>, (Annotation) -> IPersistableAnnotation>,
      keys: Map<KClass<out Annotation>, String>,
    ): KClassMetadata {
      val data: Map<String, PersistableBundle> =
        source.java.annotations
          .flatMap { unwrap(it) }
          .filter { it.annotationClass in targets }
          .groupBy { it.annotationClass }
          .map { (k, v) ->
            val key = keys.getValue(k)
            val converter = converters.getValue(k)
            val value = v.map { converter(it) }
            key to PersistableListSerializer.Strict.toPersistableBundle(value)
          }
          .toMap()
      return KClassMetadata(
        name = requireNotNull(source.java.name),
        canonicalName = requireNotNull(source.java.canonicalName),
        data = data,
      )
    }

    /**
     * Unwraps a given annotation into a List of the same annotations by checking for [Repeatable]
     * annotation container and flattening it.
     */
    private fun unwrap(annotation: Annotation): List<Annotation> {
      return try {
        val annotationClass = annotation.annotationClass.java
        // [value, equals, toString, hashCode, annotationType]
        require(annotationClass.methods.size == 5)
        val method = requireNotNull(annotationClass.getMethod("value"))
        require(method.returnType.isArray)
        require(method.returnType.componentType?.isAnnotation == true)
        @Suppress("UNCHECKED_CAST") (method.invoke(annotation) as Array<Annotation>).asList()
      } catch (_: Throwable) {
        listOf(annotation)
      }
    }
  }
}
