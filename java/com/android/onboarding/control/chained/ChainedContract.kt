    private const val KEY_CALLBACK_KEY = "cc.KEY_CALLBACK_KEY"
    private const val KEY_TYPE = "cc.TYPE"
    private const val TYPE_ACTIVITY = "Activity"
    private const val TYPE_TASK = "Task"
    private const val KEY_SUBTYPE = "cc.SUBTYPE"
    private const val KEY_HANDLES_FAILURE = "cc.HANDLES_FAILURE"
    private const val SUBTYPE_ACTIVITY_TO_TASK = "ActivityToTask"
    private const val SUBTYPE_ACTIVITY_TO_ACTIVITY = "ActivityToActivity"
    private const val SUBTYPE_TASK_TO_TASK = "TaskToTask"
    private const val SUBTYPE_TASK_TO_ACTIVITY = "TaskToActivity"

    override fun fromPersistableBundle(persistableBundle: PersistableBundle): ChainedContract<*> =
      when (val type = persistableBundle.getString(KEY_TYPE)) {
        TYPE_ACTIVITY -> Activity.fromPersistableBundle(persistableBundle)
        TYPE_TASK -> Task.fromPersistableBundle(persistableBundle)
        else -> error("Unknown ChainedContract type $type")
      }

    private fun extractCallbackUserId(bundle: PersistableBundle): Int {
      val id = bundle.getInt(KEY_CALLBACK_USER_ID, -69)
      return if (id == -69) {
        val currentUserId = Process.myUserHandle().identifier
        Log.w(TAG, "Callback user ID is not set, using current user ID: $currentUserId")
        currentUserId
      } else {
        id
      }
    }
  }
