  companion object : PersistableDeserializer<ChainedContract<*>> {
    private const val TAG = "ChainedContract"
    private const val KEY_TARGET = "cc.TARGET"
    private const val KEY_SESSION = "cc.SESSION"
    private const val KEY_STATE = "cc.STATE"
    private const val KEY_ESTIMATED_CALLBACK_RUNTIME = "cc.KEY_ESTIMATED_CALLBACK_RUNTIME"
    private const val KEY_CALLBACK_METADATA_STORE = "cc.KEY_CALLBACK_METADATA_STORE"
