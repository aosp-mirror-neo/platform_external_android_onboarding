/**
 * A contract specifying a request to launch another [target] node and then return the result by
 * launching another node generated by the [onResult].
 *
 * Nodes wishing to spawn [ChainedContracts][ChainedContract] should use [ChainedInput] for their
 * internal input handling which allows intercepting and reacting to non-standard input types
 * without needing to modify the caller APIs.
 *
 * Finally, returning [ChainedContract] does not guarantee it being actioned as it relies on the
 * caller being aware of such non-standard return values and being able to handle it. As it should
 * only be used in entities managed by the
 * [OrchestratorViewModel][com.android.onboarding.control.OrchestratorViewModel].
 *
 * @param R raw transfer layer result type used to pass around erased data until it is ready to be
 *   deserialized into a concrete type by the callback receiver. This is intentionally "invisible"
 *   to the [OrchestratorViewModel][com.android.onboarding.control.OrchestratorViewModel] as it is
 *   only meant to be handled by the originating task or activity which requested the callback in
 *   the first place. For chained contracts targeting activities this will be [ActivityResult]
 *   whereas for chained contracts targeting tasks this will be [PersistableBundle]. All direct
 *   implementations of this interface are expected to hide this generic by providing the concrete
 *   transfer layer type.
 * @sample com.android.onboarding.control.OrchestratedTaskTest.startActivityForResult
 * @sample com.android.onboarding.control.OrchestratedTaskTest.startTaskForResult
 * @see ChainedContract.Activity
 * @see ChainedContract.Task
 */
sealed interface ChainedContract<R> : Persistable, NodeRef, StableEquality {
  /** The target node to be launched for result. */
  val target: PendingContract.Erased<*>

  /** Reference to the callback node. */
  val callbackRef: UniqueNodeRef

  /** Reference to the specific callback in callback node. */
  val callbackKey: String

  /**
   * Specifies if the callback handles failures itself.
   *
   * If `false`, all failures will be handled by the orchestrator.
   */
  val handlesFailure: Boolean

  /**
   * An identifier for this [ChainedContract] providing the same uniqueness as [NodeRef].
   *
   * Built from [target] and [callbackRef] [NodeRefs][NodeRef].
   *
   * Formatted as "[callbackRef]<-[target]".
   *
   * e.g.: `com.test.component1:NodeA<-com.test.component2:NodeB`
   */
  val id: String
    get() = "${callbackRef.asNodeRef().identity()}<-${target.asNodeRef().identity()}"

  /**
   * Estimated runtime of the **callback** which will be processing the result of this
   * [ChainedContract].
   */
  val estimatedCallbackRuntime: Duration?

  override fun toPersistableBundle() = PersistableBundle {
    putPersistable(KEY_TARGET, target)
    compatPutBoolean(KEY_HANDLES_FAILURE, handlesFailure)
    putString(KEY_ESTIMATED_CALLBACK_RUNTIME, estimatedCallbackRuntime?.toIsoString())
  }

  /**
   * Wraps the [result] into a callback node contract which is expected to be launched immediately.
   * The returned pending contract contains all the required data to resume paused node and provide
   * the result it previously requested.
   *
   * @param failure does [result] represent node failure.
   */
  fun onResult(result: R, failure: Boolean = false): PendingContract.Erased<*>

  /** A [ChainedContract] requesting an activity launch. */
  sealed interface Activity : ChainedContract<ActivityResult> {
    override val target: PendingContract.ErasedActivity

    override fun toPersistableBundle() =
      super.toPersistableBundle().apply { putString(KEY_TYPE, TYPE_ACTIVITY) }

    companion object : PersistableDeserializer<Activity> {
      override fun fromPersistableBundle(persistableBundle: PersistableBundle): Activity =
        when (val subType = persistableBundle.getString(KEY_SUBTYPE)) {
          SUBTYPE_ACTIVITY_TO_TASK -> ActivityToTask.fromPersistableBundle(persistableBundle)
          SUBTYPE_ACTIVITY_TO_ACTIVITY ->
            ActivityToActivity.fromPersistableBundle(persistableBundle)
          else -> error("Unknown ChainedContract.Activity type $subType")
        }
    }
  }

  /**
   * A [ChainedContract.Activity] which uses a [Task][PendingContract.Task] callback.
   *
   * @sample com.android.onboarding.control.chained.ChainedContractTest.activityToTask_survivesSerialization
   * @sample com.android.onboarding.control.OrchestratedTaskTest.startActivityForResult
   */
  class ActivityToTask(
    private val session: PersistableBundle,
    target: PendingContract.Activity<*>,
    override val callbackRef: UniqueNodeRef,
    private val callbackServiceIntent: PersistableIntent,
    override val estimatedCallbackRuntime: Duration?,
    private val callbackMetadataStore: OnboardingMetadataStore? = null,
    override val handlesFailure: Boolean = false,
    private val callbackUserId: Int,
    private val state: PersistableBundle? = null,
    override val callbackKey: String = target.asNodeRef().identity(),
  ) : Activity, NodeRef by callbackRef, StableEquality {
    override val target = target.erase()

    override fun toString() =
      "ChainedContract.ActivityToTask(target=${target.identity()},callback=${callbackRef.identity()},callbackKey=${callbackKey},handlesFailure=$handlesFailure)"

    override fun equals(other: Any?): Boolean =
      other is ActivityToTask &&
        session contentDeepEquals other.session &&
        state contentDeepEquals other.state &&
        target == other.target &&
        callbackRef refersTo other.callbackRef &&
        callbackServiceIntent == other.callbackServiceIntent &&
        estimatedCallbackRuntime == other.estimatedCallbackRuntime &&
        callbackMetadataStore == other.callbackMetadataStore &&
        handlesFailure == other.handlesFailure &&
        callbackUserId == other.callbackUserId &&
        callbackKey == other.callbackKey

    override fun hashCode(): Int =
      Objects.hash(
        session.generateHash(),
        state.generateHash(),
        target,
        callbackRef.generateHash(),
        callbackServiceIntent,
        estimatedCallbackRuntime.hashCode(),
        callbackMetadataStore,
        handlesFailure,
        callbackUserId,
        callbackKey,
      )

    override fun onResult(result: ActivityResult, failure: Boolean): PendingContract.ErasedTask {
      val input =
        ChainedInput.ActivityCallbackInput(
          session = session,
          state = state,
          source = target,
          metadataStore = callbackMetadataStore,
          data = result,
          failure = failure,
          callbackKey = callbackKey,
        )
      @OptIn(InternalOnboardingApi::class)
      return PendingTaskContract(
        input = input.toPersistableBundle(),
        ref = callbackRef,
        creatorNodeId = callbackRef.nodeId,
        taskServiceIntent = callbackServiceIntent,
        targetUserId = callbackUserId,
      )
    }

    override fun toPersistableBundle() =
      super.toPersistableBundle().apply {
        putString(KEY_SUBTYPE, SUBTYPE_ACTIVITY_TO_TASK)
        putPersistableBundle(KEY_SESSION, session)
        putPersistableBundle(KEY_STATE, state)
        putPersistable(KEY_CALLBACK_REF, callbackRef, PersistableUniqueNodeRef)
        putPersistable(KEY_CALLBACK_SERVICE_INTENT, callbackServiceIntent)
        putInt(KEY_CALLBACK_USER_ID, callbackUserId)
        putPersistable(KEY_CALLBACK_METADATA_STORE, callbackMetadataStore)
        putString(KEY_CALLBACK_KEY, callbackKey)
      }

    companion object : PersistableDeserializer<ActivityToTask> {
      override fun fromPersistableBundle(persistableBundle: PersistableBundle): ActivityToTask {
        require(persistableBundle.getString(KEY_TYPE) == TYPE_ACTIVITY) { "Invalid type" }
        require(persistableBundle.getString(KEY_SUBTYPE) == SUBTYPE_ACTIVITY_TO_TASK) {
          "Invalid subtype"
        }
        val target =
          requireNotNull(persistableBundle.getPersistable(KEY_TARGET, PendingContract.Activity))
        return ActivityToTask(
          session = requireNotNull(persistableBundle.getPersistableBundle(KEY_SESSION)),
          state = persistableBundle.getPersistableBundle(KEY_STATE),
          target = target,
          callbackRef =
            requireNotNull(
              persistableBundle.getPersistable(KEY_CALLBACK_REF, PersistableUniqueNodeRef)
            ),
          callbackServiceIntent =
            requireNotNull(
              persistableBundle.getPersistable(KEY_CALLBACK_SERVICE_INTENT, PersistableIntent)
            ),
          callbackUserId = extractCallbackUserId(persistableBundle),
          estimatedCallbackRuntime =
            persistableBundle
              .getString(KEY_ESTIMATED_CALLBACK_RUNTIME)
              ?.let(Duration::parseIsoString),
          callbackMetadataStore =
            persistableBundle.getPersistable(KEY_CALLBACK_METADATA_STORE, OnboardingMetadataStore),
          handlesFailure = persistableBundle.compatGetBoolean(KEY_HANDLES_FAILURE, false),
          callbackKey =
            persistableBundle.getString(KEY_CALLBACK_KEY) ?: target.asNodeRef().identity(),
        )
      }
    }
  }

